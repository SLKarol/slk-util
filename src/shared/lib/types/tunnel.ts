/**
 * Представляет диапазоны IP-адресов, разделённые по версиям протокола.
 *
 * Используется для указания списка IPv4 и IPv6 адресов, которые должны быть включены
 * в туннель или обработаны определённым образом.
 */
export interface IPRange {
  /**
   * Массив строк, представляющих IPv4-адреса или подсети в формате CIDR.
   *
   * Пример: `["192.168.1.0/24", "10.0.0.1"]`
   */
  ipv4: string[];

  /**
   * Массив строк, представляющих IPv6-адреса или подсети в формате CIDR.
   *
   * Пример: `["2001:db8::/32", "::1"]`
   */
  ipv6: string[];
}
