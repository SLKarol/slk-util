/**
 * Интерфейс, представляющий раздел на сайте "Стихи.ру".
 *
 * Используется для хранения информации о блоке произведений, например, диапазоне номеров
 * и ссылке на страницу с этими произведениями.
 *
 * @example
 * ```ts
 * const chapter: SihiChapter = {
 *   textContent: "1-5",
 *   href: "/poems/1-5"
 * };
 * ```
 */
export interface SihiChapter {
  /**
   * Текстовое обозначение главы (например, "1-5", "6-10").
   * Отображается пользователю как название раздела.
   */
  textContent: string;

  /**
   * URL-адрес страницы главы на сайте "Стихи.ру".
   * Используется для навигации и загрузки содержимого.
   */
  href: string;
}

/**
 * Интерфейс, описывающий состояние автоматического чтения стихов.
 *
 * Хранит информацию о том, включён ли режим боточтения по главам,
 * а также дату издания произведений.
 */
export interface IStatusAutoReadStihi {
  /**
   * Флаг, указывающий, включён ли режим автоматического чтения по главам.
   */
  isAutoRead: boolean;
  /**
   * Дата издания произведений, которая отображается в интерфейсе и используется для фильтрации при загрузке стихов.
   */
  datePoems: string | null;
}
