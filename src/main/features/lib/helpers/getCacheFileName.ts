import { createHash } from "crypto";
import path from "path";

/**
 * Генерирует безопасное имя файла для кэширования на основе URL.
 *
 * Функция принимает URL и возвращает имя файла, пригодное для использования в файловой системе.
 * Преобразует URL следующим образом:
 * - Удаляет протокол, домен и параметры запроса.
 * - Заменяет недопустимые символы на подчёркивания.
 * - Добавляет хеш-суффикс (при необходимости, если имена могут конфликтовать).
 * - Сохраняет расширение файла, если оно присутствует в исходном URL.
 *
 * @param {string} url - Исходный URL файла, для которого нужно сгенерировать имя.
 * @returns {string} Строка с именем файла (без пути), например: `image_abc123.jpg`.
 */
export function getCacheFileName(url: string) {
  // Убираем GET-параметры из URL перед хэшированием
  const cleanUrl = url.split("?")[0];
  const hash = createHash("md5").update(cleanUrl).digest("hex");
  // Определяем расширение из очищенного URL (например, .jpg, .png)
  const ext = path.extname(cleanUrl) || ".html"; // По умолчанию .html, если не указано
  return `${hash}${ext}`;
}
